// Command gen turns the Wayland protocol XML files of protocols/ into
// internal/wl/protocols_gen.go.
//
// Opcodes are never written by hand: a request's (or event's) opcode is its
// index in the XML declaration order of the interface, which is exactly what
// this generator records. Run it with "go generate ./internal/wl/...".
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// sources are the protocol XML files, relative to internal/wl (the directory
// the //go:generate directive runs in).
var sources = []string{
	"../../protocols/wayland.xml",
	"../../protocols/wlr-virtual-pointer-unstable-v1.xml",
	"../../protocols/virtual-keyboard-unstable-v1.xml",
	"../../protocols/wlr-screencopy-unstable-v1.xml",
	"../../protocols/wlr-foreign-toplevel-management-unstable-v1.xml",
	"../../protocols/wlr-output-management-unstable-v1.xml",
	"../../protocols/xdg-shell.xml",
	"../../protocols/linux-dmabuf-v1.xml",
	"../../protocols/viewporter.xml",
	"../../protocols/hyprland-toplevel-export-v1.xml",
}

const outFile = "protocols_gen.go"

type xmlProtocol struct {
	Name       string         `xml:"name,attr"`
	Interfaces []xmlInterface `xml:"interface"`
}

type xmlInterface struct {
	Name     string       `xml:"name,attr"`
	Version  int          `xml:"version,attr"`
	Requests []xmlMessage `xml:"request"`
	Events   []xmlMessage `xml:"event"`
}

type xmlMessage struct {
	Name  string   `xml:"name,attr"`
	Type  string   `xml:"type,attr"`
	Since int      `xml:"since,attr"`
	Args  []xmlArg `xml:"arg"`
}

type xmlArg struct {
	Name      string `xml:"name,attr"`
	Type      string `xml:"type,attr"`
	Interface string `xml:"interface,attr"`
	AllowNull string `xml:"allow-null,attr"`
	Enum      string `xml:"enum,attr"`
}

var argConst = map[string]string{
	"int":    "argInt",
	"uint":   "argUint",
	"fixed":  "argFixed",
	"string": "argString",
	"object": "argObject",
	"new_id": "argNewID",
	"array":  "argArray",
	"fd":     "argFD",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	ifaces := map[string]xmlInterface{}
	origin := map[string]string{}
	for _, src := range sources {
		raw, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		var p xmlProtocol
		if err := xml.Unmarshal(raw, &p); err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		for _, in := range p.Interfaces {
			if prev, dup := ifaces[in.Name]; dup {
				return fmt.Errorf("interface %s declared twice (%s and %s)", in.Name, origin[prev.Name], src)
			}
			if in.Version == 0 {
				in.Version = 1
			}
			ifaces[in.Name] = in
			origin[in.Name] = filepath.Base(src)
		}
	}

	names := make([]string, 0, len(ifaces))
	for n := range ifaces {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/wl/gen. DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprint(&b, "// Source files:\n")
	for _, src := range sources {
		fmt.Fprintf(&b, "//   %s\n", filepath.Base(src))
	}
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package wl")
	fmt.Fprintln(&b)

	// Opcode constants.
	fmt.Fprintln(&b, "// Request opcodes (index of the request in its interface's XML order).")
	fmt.Fprintln(&b, "const (")
	for _, n := range names {
		in := ifaces[n]
		if len(in.Requests) == 0 {
			continue
		}
		for i, m := range in.Requests {
			fmt.Fprintf(&b, "\treq%s%s = %d\n", goName(n), goName(m.Name), i)
		}
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "// Event opcodes (index of the event in its interface's XML order).")
	fmt.Fprintln(&b, "const (")
	for _, n := range names {
		in := ifaces[n]
		for i, m := range in.Events {
			fmt.Fprintf(&b, "\tevt%s%s = %d\n", goName(n), goName(m.Name), i)
		}
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)

	// Interface names as constants, to keep string literals in one place.
	fmt.Fprintln(&b, "// Interface names.")
	fmt.Fprintln(&b, "const (")
	for _, n := range names {
		fmt.Fprintf(&b, "\tiface%s = %q\n", goName(n), n)
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "// protoIfaces describes every interface of the bundled protocols: its")
	fmt.Fprintln(&b, "// maximum version and, for each request and event, its opcode (the slice")
	fmt.Fprintln(&b, "// index) and argument signature.")
	fmt.Fprintln(&b, "var protoIfaces = map[string]*ifaceSpec{")
	for _, n := range names {
		in := ifaces[n]
		fmt.Fprintf(&b, "\t%q: {\n", n)
		fmt.Fprintf(&b, "\t\tName:    %q,\n", n)
		fmt.Fprintf(&b, "\t\tVersion: %d,\n", in.Version)
		writeMessages(&b, "Requests", in.Requests)
		writeMessages(&b, "Events", in.Events)
		fmt.Fprintln(&b, "\t},")
	}
	fmt.Fprintln(&b, "}")

	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(outFile+".broken", b.Bytes(), 0o644)
		return fmt.Errorf("gofmt: %w", err)
	}
	return os.WriteFile(outFile, src, 0o644)
}

func writeMessages(b *bytes.Buffer, field string, msgs []xmlMessage) {
	if len(msgs) == 0 {
		return
	}
	fmt.Fprintf(b, "\t\t%s: []msgSpec{\n", field)
	for i, m := range msgs {
		since := m.Since
		if since == 0 {
			since = 1
		}
		fmt.Fprintf(b, "\t\t\t{Name: %q, Opcode: %d, Since: %d", m.Name, i, since)
		if m.Type == "destructor" {
			fmt.Fprint(b, ", Destructor: true")
		}
		if len(m.Args) > 0 {
			fmt.Fprint(b, ", Args: []argSpec{")
			for j, a := range m.Args {
				if j > 0 {
					fmt.Fprint(b, ", ")
				}
				t, ok := argConst[a.Type]
				if !ok {
					panic("unknown arg type " + a.Type)
				}
				fmt.Fprintf(b, "{Name: %q, Type: %s", a.Name, t)
				if a.Interface != "" {
					fmt.Fprintf(b, ", Interface: %q", a.Interface)
				}
				if a.AllowNull == "true" {
					fmt.Fprint(b, ", Nullable: true")
				}
				fmt.Fprint(b, "}")
			}
			fmt.Fprint(b, "}")
		}
		fmt.Fprintln(b, "},")
	}
	fmt.Fprintln(b, "\t\t},")
}

// goName turns a snake_case protocol name into a CamelCase Go identifier
// fragment: "zwlr_virtual_pointer_v1" -> "ZwlrVirtualPointerV1".
func goName(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}
